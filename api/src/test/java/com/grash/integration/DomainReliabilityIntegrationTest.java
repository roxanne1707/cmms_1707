    private Part part(Long id,boolean lock) {return jdbc.query("SELECT * FROM part WHERE id=?"+(lock?" FOR UPDATE":""),(rs,n)->{Part p=new Part();p.setId(id);p.setCompany(company);p.setName("Bearing");p.setQuantity(rs.getDouble("quantity"));p.setVersion(rs.getLong("version"));return p;},id).stream().findFirst().orElse(null);}
