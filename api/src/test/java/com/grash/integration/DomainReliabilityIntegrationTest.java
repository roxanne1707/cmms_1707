    @Test void stockDetailAuditAndCommandRollbackTogether() {
        failQuantity.set(true);
        assertThrows(IllegalStateException.class,()->inventory.create(request(10L,7),user,"rollback"));
        assertEquals(10,stock());assertEquals(0,count("part_transaction"));assertEquals(0,count("part_quantity"));assertEquals(0,count("domain_command"));
    }
    @Test void zeroDeltaReturnDeletionAndReplayPreserveLedger() {
        PartQuantityShowDTO original=inventory.create(request(10L,3),user,"create");
        assertEquals(original.getId(),inventory.create(request(10L,3),user,"create").getId());
        inventory.setQuantity(original.getId(),3,user,"same");assertEquals(1,count("part_transaction"));
        inventory.setQuantity(original.getId(),1,user,"return");
        inventory.delete(original.getId(),user,"delete");inventory.delete(original.getId(),user,"delete");
        assertEquals(10,stock());assertEquals(3,count("part_transaction"));assertEquals(0,count("part_quantity"));
        assertEquals(0,jdbc.queryForObject("SELECT sum(quantity) FROM part_transaction",Double.class));
    }
    @Test void commandCannotBeReusedWithDifferentPayloadAndRevocationIsCheckedOnReplay() {
        inventory.create(request(10L,3),user,"create");
        assertThrows(CustomException.class,()->inventory.create(request(10L,4),user,"create"));
        user.getRole().getEditOtherPermissions().clear();
        assertThrows(CustomException.class,()->inventory.create(request(10L,3),user,"create"));assertEquals(7,stock());assertEquals(1,count("part_transaction"));
    }
    @Test void simultaneousDifferentWorkOrdersCannotOverspendOnePart() throws Exception {
        ExecutorService pool=Executors.newFixedThreadPool(2);CyclicBarrier gate=new CyclicBarrier(2);
        try {
            Callable<Boolean> a=()->{gate.await(5,TimeUnit.SECONDS);try{inventory.create(request(10L,7),user,"a");return true;}catch(CustomException e){return false;}};
            Callable<Boolean> b=()->{gate.await(5,TimeUnit.SECONDS);try{inventory.create(request(20L,7),user,"b");return true;}catch(CustomException e){return false;}};
            Future<Boolean> first=pool.submit(a),second=pool.submit(b);assertNotEquals(first.get(15,TimeUnit.SECONDS),second.get(15,TimeUnit.SECONDS));
            assertEquals(3,stock());assertEquals(1,count("part_quantity"));assertEquals(1,count("part_transaction"));
        } finally {pool.shutdownNow();}
    }
    @Test void bulkRemovalReturnsStockInsteadOfDiscardingConsumption() {
        inventory.replaceWorkOrder(10L,List.of(1L),user,"associate");
        assertEquals(9,stock());
        inventory.replaceWorkOrder(10L,List.of(),user,"remove");
        assertEquals(10,stock());
        assertEquals(0,count("part_quantity"));
        assertEquals(2,count("part_transaction"));
        assertEquals(0,jdbc.queryForObject("SELECT sum(quantity) FROM part_transaction",Double.class));
    }

